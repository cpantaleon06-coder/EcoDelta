// Rewrites the package tables in THIRD_PARTY.md (from "## Direct dependencies" down) from the installed node_modules.
// Usage: node scripts/third-party.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(`${web}/package.json`, 'utf8'));
const lock = JSON.parse(readFileSync(`${web}/package-lock.json`, 'utf8')).packages;
const installed = Object.entries(lock)
  .filter(([path]) => path && existsSync(`${web}/${path}`)) // skip optional binaries for other platforms
  .map(([path, p]) => ({ name: path.slice(path.lastIndexOf('node_modules/') + 13), version: p.version, license: p.license ?? 'UNKNOWN', dev: !!p.dev }));
const unique = (list) => [...new Map(list.map((p) => [`${p.name}@${p.version}`, p])).values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const table = (list) => ['| Package | Version | License |', '|---|---|---|', ...list.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`)].join('\n');
const counts = (list) =>
  Object.entries(list.reduce((c, p) => ({ ...c, [p.license]: (c[p.license] ?? 0) + 1 }), {}))
    .sort((a, b) => b[1] - a[1])
    .map(([l, n]) => `${l}: ${n}`)
    .join(', ');
const top = (name) => installed.find((p) => p.name === name && !p.name.includes('/node_modules/'));
const roles = { 'maplibre-gl': 'Map rendering', react: 'UI', 'react-dom': 'UI', 'react-router-dom': 'Page routing', recharts: 'Charts', '@fontsource/space-grotesk': 'The one font (self-hosted)', 'world-atlas': 'Land data for the hero globe mask (build time only)', 'topojson-client': 'Decodes world-atlas when building the mask (build time only)' };
const direct = [...Object.keys(pkg.dependencies), ...Object.keys(pkg.devDependencies)].map((n) => {
  const p = top(n);
  return `| ${n} | ${p.version} | ${p.license} | ${roles[n] ?? 'Development only'} |`;
});
const prod = unique(installed.filter((p) => !p.dev));
const dev = unique(installed.filter((p) => p.dev));
const body = `## Direct dependencies

| Package | Version | License | Role |
|---|---|---|---|
${direct.join('\n')}

## All packages shipped in the website (production tree, ${prod.length} packages)

License count: ${counts(prod)}.

${table(prod)}

## All development-only packages (${dev.length} packages, not shipped)

License count: ${counts(dev)}. \`caniuse-lite\` (CC-BY-4.0) is browser support data used only at build time.

${table(dev)}

Generated by \`node scripts/third-party.mjs\` from the installed \`node_modules\` and \`package-lock.json\`.
`;
const file = `${web}/THIRD_PARTY.md`;
const doc = readFileSync(file, 'utf8');
writeFileSync(file, doc.slice(0, doc.indexOf('## Direct dependencies')) + body);
console.log(`production ${prod.length}, development ${dev.length}`);

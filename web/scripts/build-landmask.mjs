// Usage: node scripts/build-landmask.mjs   Writes src/hero/landMask.ts, the land mask of the decorative hero globe.
// Source: src/assets/land-50m.json (made by build-land.mjs from Natural Earth 1:50m land, public domain), the same
// land the map basemap draws. Its rings are already closed around the pole. Run once; the output is committed.
import { readFileSync, writeFileSync } from 'node:fs';

const W = 360; // 1 degree cells, west to east from -180
const H = 180; // north to south from +90
const land = JSON.parse(readFileSync(new URL('../src/assets/land-50m.json', import.meta.url)));
const rings = land.features.flatMap((f) => f.geometry.coordinates.flat());

// even-odd rule on the lon/lat plane, tested at each cell center
const inside = (x, y) => {
  let c = false;
  for (const r of rings)
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i];
      const [xj, yj] = r[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
  return c;
};

const rows = [];
for (let i = 0; i < H; i++) {
  let hex = '';
  for (let j = 0; j < W; j += 4) {
    let nib = 0;
    for (let k = 0; k < 4; k++) nib = (nib << 1) | (inside(-180 + (360 / W) * (j + k + 0.5), 90 - (180 / H) * (i + 0.5)) ? 1 : 0);
    hex += nib.toString(16);
  }
  rows.push(hex);
}
writeFileSync(
  new URL('../src/hero/landMask.ts', import.meta.url),
  `// Generated by scripts/build-landmask.mjs from src/assets/land-50m.json (Natural Earth 1:50m land, public domain).
// ${W} x ${H} cells of ${360 / W} degree; row 0 is the northernmost, column 0 starts at 180W. Each hex digit holds 4 cells, 1 = land.
export const MASK_W = ${W};
export const MASK_H = ${H};
export const LAND_ROWS = [
${rows.map((r) => `  '${r}',`).join('\n')}
];
`,
);
const landCells = rows.join('').split('').reduce((n, h) => n + [...parseInt(h, 16).toString(2)].filter((b) => b === '1').length, 0);
console.log(`land cells: ${landCells} of ${W * H} (${((100 * landCells) / (W * H)).toFixed(1)}%)`);

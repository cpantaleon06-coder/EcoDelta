// Usage: node scripts/build-landmask.mjs   Writes src/hero/landMask.ts, the land mask of the decorative hero globe.
// Source: Natural Earth 1:110m land (public domain) via the world-atlas package (ISC). Run once; the output is committed.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const W = 360; // 1 degree cells, west to east from -180
const H = 180; // north to south from +90
const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)));
// A ring edge that jumps across the dateline (Antarctica) is closed around the pole instead of straight across the map.
const closeAtPole = (r) =>
  r.flatMap((p, i) => {
    const q = r[i + 1];
    if (!q || Math.abs(q[0] - p[0]) <= 180) return [p];
    const e = Math.sign(p[0]) * 180;
    const pole = p[1] < 0 ? -90 : 90;
    return [p, [e, p[1]], [e, pole], [-e, pole], [-e, q[1]]];
  });
const rings = feature(topo, topo.objects.land)
  .features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates).flat())
  .map(closeAtPole);

// even-odd rule on the lon/lat plane, tested at each cell center
const inside = (x, y) => {
  let c = false;
  for (const r of rings)
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i];
      const [xj, yj] = r[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
    }
  return c;
};

const rows = [];
for (let i = 0; i < H; i++) {
  let hex = '';
  for (let j = 0; j < W; j += 4) {
    let nib = 0;
    for (let k = 0; k < 4; k++) nib = (nib << 1) | (inside(-180 + (360 / W) * (j + k + 0.5), 90 - (180 / H) * (i + 0.5)) ? 1 : 0);
    hex += nib.toString(16);
  }
  rows.push(hex);
}
writeFileSync(
  new URL('../src/hero/landMask.ts', import.meta.url),
  `// Generated by scripts/build-landmask.mjs from Natural Earth 1:110m land (public domain), via world-atlas (ISC).
// ${W} x ${H} cells of ${360 / W} degree; row 0 is the northernmost, column 0 starts at 180W. Each hex digit holds 4 cells, 1 = land.
export const MASK_W = ${W};
export const MASK_H = ${H};
export const LAND_ROWS = [
${rows.map((r) => `  '${r}',`).join('\n')}
];
`,
);
const land = rows.join('').split('').reduce((n, h) => n + [...parseInt(h, 16).toString(2)].filter((b) => b === '1').length, 0);
console.log(`land cells: ${land} of ${W * H} (${((100 * land) / (W * H)).toFixed(1)}%)`);
